"""
Stage 2 of the CMF fit.

    python3 model-fit/fit.py

Fits   CMF = 1 - sum_i a_i * c_i**b_i,   i in {low, mid, high},   c_i in [0, 1]
with   0.50 <= a_low + a_mid + a_high <= 0.60
       (full overcast in every layer -> 50-60 % reduction, Allaart et al. 2004)

Fit target: Open-Meteo uv_index / Open-Meteo uv_index_clear_sky.
NOTE: this is fitting to ANOTHER MODEL'S output, not to ground radiometers.
We divide by Open-Meteo's own clear-sky value (not our Allaart value) because
the two clear-sky curves disagree as a function of SZA (see report): dividing by
Allaart would fold that zenith-angle bias into the "cloud" factor.

Writes:
  app/src/model/cmfParams.ts   (generated; imported by the app)
  model-fit/report.md          (numbers for the slide)
  model-fit/cmf_fit.png        (figure for the slide)
"""
import json
import warnings

warnings.filterwarnings("ignore", message="Values in x were outside bounds")
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.optimize import minimize

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
LAYERS = ["low", "mid", "high"]
MIN_CLEAR_UVI = 1.0  # ratios at tiny UVI are dominated by rounding (OM gives 0.05 steps)
SUM_BOUNDS = (0.50, 0.60)


def load():
    d = pd.read_csv(HERE / "data" / "hourly.csv")
    d = d[d.uvi_om_clear >= MIN_CLEAR_UVI].copy()
    d["y"] = (d.uvi_om / d.uvi_om_clear).clip(upper=1.0)
    for l in LAYERS:
        d[l] = d[f"c_{l}"] / 100.0
    d["w"] = d.uvi_om_clear  # weight by dose relevance: noon hours matter more
    return d.reset_index(drop=True)


def cmf(p, C):
    a, b = p[:3], p[3:]
    return 1.0 - (a * np.power(C, b)).sum(axis=1)


def fit(d, constrained=True):
    C = d[LAYERS].to_numpy()
    y, w = d.y.to_numpy(), d.w.to_numpy()

    def loss(p):
        r = cmf(p, C) - y
        return float((w * r * r).sum() / w.sum())

    cons = []
    if constrained:
        cons = [
            {"type": "ineq", "fun": lambda p: p[:3].sum() - SUM_BOUNDS[0]},
            {"type": "ineq", "fun": lambda p: SUM_BOUNDS[1] - p[:3].sum()},
        ]
    bounds = [(0, 1)] * 3 + [(0.2, 8)] * 3
    best = None
    for a0 in ([0.3, 0.15, 0.1], [0.2, 0.2, 0.15], [0.4, 0.1, 0.05]):
        for b0 in ([1.5] * 3, [3] * 3):
            r = minimize(loss, np.array(a0 + b0), method="SLSQP", bounds=bounds, constraints=cons)
            if best is None or r.fun < best.fun:
                best = r
    return best.x, best.fun


def metrics(p, d):
    pred = cmf(p, d[LAYERS].to_numpy())
    y, w = d.y.to_numpy(), d.w.to_numpy()
    rmse = np.sqrt((w * (pred - y) ** 2).sum() / w.sum())
    bias = (w * (pred - y)).sum() / w.sum()
    ybar = (w * y).sum() / w.sum()
    r2 = 1 - (w * (pred - y) ** 2).sum() / (w * (y - ybar) ** 2).sum()
    return rmse, bias, r2


def total_cover_baseline(d):
    """Same functional family but using one total-cover number (what we argue is lossy)."""
    tot = d[LAYERS].max(axis=1).to_numpy()  # proxy for total cover
    y, w = d.y.to_numpy(), d.w.to_numpy()

    def loss(p):
        r = 1 - p[0] * tot ** p[1] - y
        return float((w * r * r).sum() / w.sum())

    r = minimize(loss, [0.5, 2], bounds=[(0, 1), (0.2, 8)],
                 constraints=[{"type": "ineq", "fun": lambda p: p[0] - SUM_BOUNDS[0]},
                              {"type": "ineq", "fun": lambda p: SUM_BOUNDS[1] - p[0]}],
                 method="SLSQP")
    pred = 1 - r.x[0] * tot ** r.x[1]
    return np.sqrt((w * (pred - y) ** 2).sum() / w.sum())


def loco(d, constrained=True):
    """Leave-one-city-out cross-validation."""
    out = {}
    for city in sorted(d.city.unique()):
        p, _ = fit(d[d.city != city], constrained)
        out[city] = metrics(p, d[d.city == city])[0]
    return out


def main():
    d = load()
    p_c, _ = fit(d, True)
    p_u, _ = fit(d, False)
    m_c, m_u = metrics(p_c, d), metrics(p_u, d)
    cv = loco(d, True)
    rmse_total = total_cover_baseline(d)
    ones = np.ones((1, 3))
    raw = pd.read_csv(HERE / "data" / "hourly.csv")
    raw = raw[raw.uvi_om_clear >= MIN_CLEAR_UVI]
    raw = raw.assign(szab=pd.cut(raw.sza_mid, [0, 20, 35, 50, 65, 75, 85]))
    cs = (raw.uvi_allaart / raw.uvi_om_clear).groupby(raw.szab, observed=True).median()

    params = {
        "a": dict(zip(LAYERS, np.round(p_c[:3], 4).tolist())),
        "b": dict(zip(LAYERS, np.round(p_c[3:], 4).tolist())),
    }
    ts = f"""// GENERATED by model-fit/fit.py. Do not edit by hand.
// CMF = 1 - sum_i a_i * c_i^b_i, c_i in [0, 1], fitted to Open-Meteo
// uv_index / uv_index_clear_sky over {len(d)} hourly points ({d.city.nunique()} cities, 4 seasons, 2025).
// Constrained: sum(a) in [{SUM_BOUNDS[0]}, {SUM_BOUNDS[1]}] (Allaart et al. 2004 overcast reduction).
// Weighted RMSE {m_c[0]:.3f}, leave-one-city-out RMSE {np.mean(list(cv.values())):.3f}.
export const CMF_PARAMS = {json.dumps(params, indent=2)} as const;

export const CMF_FIT_INFO = {{
  points: {len(d)},
  cities: {d.city.nunique()},
  rmse: {m_c[0]:.4f},
  locoRmse: {np.mean(list(cv.values())):.4f},
  target: 'Open-Meteo uv_index / uv_index_clear_sky (model output, not radiometers)',
}} as const;
"""
    (ROOT / "app" / "src" / "model" / "cmfParams.ts").write_text(ts)

    def fmt(p):
        return " | ".join(f"{l}: a={p[i]:.3f}, b={p[3+i]:.2f}" for i, l in enumerate(LAYERS))

    lines = [
        "# CMF fit report (generated by fit.py)",
        "",
        f"**Data:** {len(d)} daytime hourly points (clear-sky UVI >= {MIN_CLEAR_UVI}), "
        f"{d.city.nunique()} cities, 4 three-week windows in 2025 (Jan/Apr/Jul/Oct).",
        "",
        "**Target:** Open-Meteo `uv_index / uv_index_clear_sky`. This is another model's output, "
        "**not ground-truth radiometers**. Weighted by clear-sky UVI.",
        "",
        "## Fitted parameters",
        "",
        f"- Constrained (shipped), sum(a)={p_c[:3].sum():.3f}: {fmt(p_c)}",
        f"  - weighted RMSE {m_c[0]:.3f}, bias {m_c[1]:+.3f}, R² {m_c[2]:.3f}",
        f"  - full overcast (all layers 100%): CMF = {cmf(p_c, ones)[0]:.3f}",
        f"- Unconstrained, sum(a)={p_u[:3].sum():.3f}: {fmt(p_u)}",
        f"  - weighted RMSE {m_u[0]:.3f}, bias {m_u[1]:+.3f}, R² {m_u[2]:.3f}",
        f"  - full overcast: CMF = {cmf(p_u, ones)[0]:.3f}",
        f"- Baseline using one total-cover number (constrained): RMSE {rmse_total:.3f}",
        "",
        "## Leave-one-city-out RMSE (constrained)",
        "",
        "| city | RMSE |",
        "|---|---|",
        *[f"| {k} | {v:.3f} |" for k, v in cv.items()],
        f"| **mean** | **{np.mean(list(cv.values())):.3f}** |",
        "",
        "## Clear-sky cross-check: Allaart (TEMIS 2017) / Open-Meteo clear-sky, median by SZA",
        "",
        "| SZA band | ratio |",
        "|---|---|",
        *[f"| {k} | {v:.3f} |" for k, v in cs.items()],
        "",
        "## Known limitations",
        "",
        "- Fit target is model output, not radiometer data (EPA/NOAA UV network would be stronger).",
        "- The form 1 - sum(a c^b) is bounded above by 1, so it cannot represent broken-cloud "
        "enhancement (UVI briefly above clear sky). Open-Meteo can't either: "
        f"{(raw.uvi_om > raw.uvi_om_clear * 1.001).mean():.2%} of its hours exceed clear sky.",
        "- Cloud *fraction* does not encode optical depth: scatter at a given cover is large.",
        "- Layers combine super-additively in Open-Meteo (all three overcast cuts far more than "
        "the sum of each alone); the additive form compromises.",
    ]
    (HERE / "report.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))

    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        fig, ax = plt.subplots(figsize=(7, 4.2), dpi=150)
        xs = np.linspace(0, 1, 101)
        colors = {"low": "#2563eb", "mid": "#16a34a", "high": "#9333ea"}
        others = {"low": ["mid", "high"], "mid": ["low", "high"], "high": ["low", "mid"]}
        for i, l in enumerate(LAYERS):
            ax.plot(xs * 100, 1 - p_c[i] * xs ** p_c[3 + i], color=colors[l], lw=2, label=f"{l} cloud (fit)")
            sub = d[(d[others[l][0]] < 0.1) & (d[others[l][1]] < 0.1)]
            bins = pd.cut(sub[l], np.linspace(0, 1, 11), include_lowest=True)
            g = sub.groupby(bins, observed=True).y.mean()
            ax.plot([iv.mid * 100 for iv in g.index], g.values, "o", color=colors[l], ms=4, alpha=0.7)
        ax.set_xlabel("layer cloud cover (%)  [dots: binned Open-Meteo, other layers < 10%]")
        ax.set_ylabel("cloud modification factor")
        ax.set_ylim(0, 1.05)
        ax.grid(alpha=0.3)
        ax.legend(frameon=False)
        ax.set_title("CMF fitted to Open-Meteo model output (not radiometers)", fontsize=10)
        fig.tight_layout()
        fig.savefig(HERE / "cmf_fit.png")
    except ImportError:
        pass


if __name__ == "__main__":
    main()
